// Renders the built-in exercises' 3D animations into smooth 30 fps loops bundled in the Android app,
// so the workout widget's exercise card plays them natively (docs/android-app.md).
//
//   node scripts/widget-frames.mjs
//
// Needs Playwright's Chromium. Writes, for each exercise in src/data/exercises.json:
//   android/app/src/main/res/drawable-nodpi/wf_<id>_<n>.webp   the frames
//   android/app/src/main/res/drawable/wa_<id>.xml              an animation-list with each frame's duration
//   android/app/src/main/res/layout/widget_anim_<id>.xml       a ProgressBar that plays it (works in widgets)
// Re-run after changing an exercise's animation.
import { createRequire } from "node:module";
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { createServer } from "vite";

const require = createRequire(import.meta.url);
const { chromium } = require("playwright");

const FPS = 30, W = 384, H = 288, QUALITY = 0.82;
const RES = "android/app/src/main/res";
const res = (name) => name.replace(/[^a-z0-9]/g, "_");

const data = JSON.parse(readFileSync("src/data/exercises.json", "utf8"));
const exercises = Array.isArray(data) ? data : data.exercises;
const only = process.argv.slice(2);

for (const dir of ["drawable-nodpi", "drawable", "layout"]) mkdirSync(join(RES, dir), { recursive: true });
const clean = (dir, re) => readdirSync(join(RES, dir)).filter((f) => re.test(f)).forEach((f) => rmSync(join(RES, dir, f)));

const server = await createServer({ server: { port: 5181, strictPort: true }, logLevel: "error" });
await server.listen();
const browser = await chromium.launch({ args: ["--use-gl=swiftshader", "--enable-unsafe-swiftshader"] });
const page = await browser.newPage();
await page.goto("http://localhost:5181/");

for (const ex of exercises) {
  if (only.length && !only.includes(ex.id)) continue;
  const id = res(ex.id);
  const t = Date.now();
  const loop = await page.evaluate(async ({ ex, FPS, W, H, QUALITY }) => {
    const { renderLoop } = await import("/src/native/frames.ts");
    return renderLoop(ex, { fps: FPS, w: W, h: H, quality: QUALITY });
  }, { ex, FPS, W, H, QUALITY });

  clean("drawable-nodpi", new RegExp(`^wf_${id}_\\d+\\.webp$`));
  loop.frames.forEach((url, i) => writeFileSync(join(RES, "drawable-nodpi", `wf_${id}_${i}.webp`), Buffer.from(url.split(",")[1], "base64")));
  writeFileSync(join(RES, "drawable", `wa_${id}.xml`),
    `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/widget-frames.mjs: ${ex.name}, ${FPS} fps. -->\n` +
    `<animation-list xmlns:android="http://schemas.android.com/apk/res/android" android:oneshot="false">\n` +
    loop.frames.map((_, i) => `    <item android:drawable="@drawable/wf_${id}_${i}" android:duration="${loop.durations[i]}" />`).join("\n") +
    `\n</animation-list>\n`);
  writeFileSync(join(RES, "layout", `widget_anim_${id}.xml`),
    `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/widget-frames.mjs. An indeterminate ProgressBar is the widget-safe way to run a frame animation. -->\n` +
    `<FrameLayout xmlns:android="http://schemas.android.com/apk/res/android"\n    android:layout_width="match_parent"\n    android:layout_height="match_parent"\n    android:layoutDirection="ltr">\n\n` +
    `    <ProgressBar\n        android:layout_width="192dp"\n        android:layout_height="144dp"\n        android:layout_gravity="center"\n` +
    `        android:indeterminate="true"\n        android:indeterminateOnly="true"\n        android:indeterminateDrawable="@drawable/wa_${id}" />\n</FrameLayout>\n`);
  console.log(`${ex.id}: ${loop.frames.length} frames, ${loop.durations.reduce((a, b) => a + b, 0)} ms, ${((Date.now() - t) / 1000).toFixed(1)} s`);
}

await browser.close();
await server.close();
